def shade(c, k):
    return tuple(min(255, int(v + (255 - v) * k)) for v in c[:3]) + (255,)

os.makedirs(OUT, exist_ok=True)
for key, rows in ICONS.items():
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), key
    base = COLORS[key] + (255,)
    pal = {'#': INK, 'o': base, 'h': shade(base, 0.55), 'w': (255, 255, 255, 255)}
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != '.':
                im.putpixel((x, y), pal[ch])
    path = os.path.join(OUT, f'stat_{key}.png')
    im.save(path)
    meta = path + '.meta'
    if not os.path.exists(meta):  # GUID는 처음 한 번만(재생성해도 참조 유지). 나머지 항목은 Unity가 기본값으로 채운다.
        open(meta, 'w', encoding='utf-8', newline='\n').write(META.format(guid=uuid.uuid4().hex))

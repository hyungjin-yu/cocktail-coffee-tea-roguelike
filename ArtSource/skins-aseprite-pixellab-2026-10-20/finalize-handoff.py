"""Finalize provenance and frozen handoff metadata; no image editing."""
import csv, hashlib, json
from pathlib import Path
ROOT=Path(__file__).resolve().parent
def load(p):return json.loads(Path(p).read_text(encoding='utf-8-sig'))
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def save(p,v):Path(p).write_text(json.dumps(v,ensure_ascii=False,indent=2),encoding='utf-8')
audit=load(ROOT/'audit-results.json');assert audit['frameCount']==255 and not audit['failures'] and not audit['floorPlaneFailures']
source=load(ROOT/'source-frame-contract.json');source_checks=[]
for job,group in source['jobs'].items():
    for a in group['frames']:
        check={'filename':a['filename'],'sourceUnchanged':sha(a['source'])==a['sourceSHA256'],
               'metaUnchanged':sha(a['sourceMeta'])==a['sourceMetaSHA256'],
               'previousSkinUnchanged':sha(a['existingSkinReference'])==a['existingSkinSHA256']}
        assert all(check[k] for k in ('sourceUnchanged','metaUnchanged','previousSkinUnchanged')),check
        source_checks.append(check)
save(ROOT/'protected-source-audit.json',{'observedUniqueSourceFrames':65,'failures':0,'frames':source_checks})
generation=load(ROOT/'generation-log.json');assert len(generation['calls'])==1
call=generation['calls'][0]
call.update({'status':'success_reference_used_in_approved_rail_native','nativeSHA256':sha(ROOT/'rail-pixellab-raw.aseprite'),
             'finishedEvidence':'evidence/rail-finished.png','rawNativeReadback':'evidence/rail-raw-readback.log',
             'rawNativeFrames':2,'outputNonzeroAlpha':11112,'inputPixelsExact':True,'outputPixelsExact':True,
             'deviations':'Raw added an unrequested sword. Production native retains the actual generated cap and authors the jacket/lapels/chain; original empty hands and feet are preserved.'})
direct=[];artifacts=[];mapping=[]
for s in audit['skins']:
    path=Path(s['manifest']);m=load(path);skinid=m['skinId']
    artifacts.append({'skinId':skinid,'job':m['job'],'frameCount':len(m['frames']),'manifest':str(path),'manifestSHA256':sha(path)})
    if skinid!='skin_bartender_rail':direct.append({'skinId':skinid,'method':'Direct native Aseprite Lua drawing of the79 design','PixelLabCalls':0,'seed':None,'script':'author-outfits.lua','authorization':'coordinator msg_aa49f7cc7084','status':'coordinator_approved'})
    for f in m['frames']:
        assert set(f['alphaValues'])<={0,255},(skinid,f['filename'],'non-binary alpha')
        assert sha(f['output'])==f['outputSHA256'] and sha(f['native'])==f['nativeSHA256'],(skinid,f['filename'],'frozen artifact changed')
        mapping.append({'skinId':skinid,**{k:f[k] for k in ('filename','source','sourceSHA256','sourceMetaSHA256','output','outputSHA256','native','nativeSHA256','nativeTag','sizePx','pivotNormalized','pixelsPerUnit','anchors')}})
generation['directNativeAuthorship']=direct
generation['truthfulScope']='One actual PixelLab GUI edit call supplies rail reference; nine other designs were directly drawn in native Aseprite, not generated by PixelLab.'
save(ROOT/'generation-log.json',generation)
overlay=load(ROOT/'sword-overlay-manifest.json')
approval={'status':'ready_frozen','coordinatorVisualAccepted':True,'newSkinCount':10,'bodyPNG':255,'bodyNative':255,
          'existingSwordOverlayPNG':5,'existingSwordOverlayNative':5,'canonicalPNGCount':260,'canonicalNativeCount':260,
          'rawGenerationNativeCount':1,'PixelLabActualCalls':1,'nativeDirectDesignCount':9,
          'approvalMessages':{'rail':'msg_7865e5a658aa','allTen':'msg_1bc9a697cb16','swordOverlays':'msg_f3081eb6942e'},
          'sourceAudit':'audit-results.json','protectedSources':'protected-source-audit.json','generationLog':'generation-log.json',
          'generationLogSHA256':sha(ROOT/'generation-log.json'),'skinManifests':artifacts,'bodyFrames':mapping,
          'swordOverlayManifest':'sword-overlay-manifest.json','swordOverlayManifestSHA256':sha(ROOT/'sword-overlay-manifest.json'),
          'comparisons':['comparison-ten-idle.png','comparison-original-previous-new.png','comparison-mirrored-128.png','comparison-small-64.png'],
          'runtimeScope':'Bartender23 x5; tea28 x5 (base23 + sword03..07). Observed historical bow11 and sword00..02 remain source metadata only, accepted by coordinator msg_bf0f6c514b74.',
          'integration':'Source ready only; Unity import/runtime/combat/commerce verification belongs to Claude.',
          'noncanonicalLeftovers':'rail-candidate/ (10 historical partial candidates), rail-candidate-manifest.json and its author script remain because cleanup command was blocked by automatic approval review. Never import these.'}
save(ROOT/'asset_mapping_manifest.json',approval)
with (ROOT/'final-source-sha256.csv').open('w',newline='',encoding='utf-8') as f:
    w=csv.writer(f);w.writerow(['bundle','filename','PNG_SHA256','native_SHA256'])
    for row in mapping:w.writerow([row['skinId'],row['filename'],row['outputSHA256'],row['nativeSHA256']])
    for row in overlay['frames']:w.writerow(['existing_sword_overlay',row['filename'],row['outputSHA256'],row['nativeSHA256']])
print('FROZEN_HANDOFF ten skins, body255 + overlay5, canonical PNG260/native260, protected source65 exact')
